from pipeline.models import Cell
from pipeline.pilotcopy import fill
from pipeline.settings import ROOT, Config

ADMIN_EMAIL = "swallehmtawazo@gmail.com"

# Keys the dashboard can edit: the pipeline only inserts them if missing (dashboard edits win).
DASHBOARD_OWNED_KEYS = {"quick_replies", "followup_templates", "demo_cap", "daily_mix", "outreach_whatsapp", "pause_list"}


def settings_payload(cfg: Config) -> dict[str, object]:
    cal = cfg.calendar
    return {
        "calendar": {
            "timezone": cal.timezone,
            "send_days": cal.send_days,
            "holidays": [{"date": h.date.isoformat(), "name": h.name} for h in cal.holidays],
            "pauses": [{"start": p.start.isoformat(), "end": p.end.isoformat(), "name": p.name} for p in cal.pauses],
            "pauses_block_followups": cal.pauses_block_followups,
            "followups": cal.followups,
            "pacing": cal.pacing,
            "same_day_demo_cutoff": cal.same_day_demo_cutoff,
        },
        "subcategories": {
            k: {"label": s.label, "active": s.active, "template": s.template}
            for k, s in cfg.subcategories.items()
        },
        "scoring": {"ads_min_score": cfg.scoring.ads.min_score},
        "pilot": cfg.pilot.model_dump(),
        "messaging": {
            "signoff": cfg.messaging.signoff,
            "length": cfg.messaging.length,
        },
        "budget": {
            "places_calls_per_month": cfg.budget.places.calls_per_month,
            "places_calls_per_night": cfg.budget.places.calls_per_night,
            "psi_calls_per_night": cfg.budget.psi.calls_per_night,
            "gemini_calls_per_night": cfg.budget.gemini.calls_per_night,
            "db_cap_mb": cfg.budget.retention.db_cap_mb,
            "storage_cap_mb": cfg.budget.retention.storage_cap_mb,
        },
        # dashboard-owned (seeded once)
        "quick_replies": [{**q.model_dump(), "text": fill(q.text, cfg)} for q in cfg.messaging.quick_replies],
        "followup_templates": {k: fill(v, cfg) for k, v in cfg.messaging.followups.items()},
        "demo_cap": cfg.calendar.demo_cap,
        "daily_mix": cfg.scoring.selection.daily_mix,
        "outreach_whatsapp": "",
        "pause_list": [],
    }


def config_cells(cfg: Config) -> list[Cell]:
    """Every (subcategory, query template, area) cell the config allows."""
    cells: list[Cell] = []
    for key, sub in cfg.subcategories.items():
        for area in cfg.areas.areas:
            if area.tier == 1 and sub.area_set not in area.sets:
                continue
            if area.tier == 3 and not sub.tier3_enabled:
                continue
            for q in sub.queries:
                cells.append(Cell(subcategory=key, query_template=q, area=area.name, tier=area.tier))
    return cells


def _q(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def generate_seed_sql(cfg: Config, admin_email: str = ADMIN_EMAIL) -> str:
    lines = [
        "-- GENERATED by `python -m pipeline gen-seed` from config/*.yaml. Do not edit by hand.",
        "-- Apply with: supabase db push --include-seed   (or paste into the SQL editor).",
        "-- Re-running is safe: existing rows are kept (dashboard edits win).",
        "",
        "insert into public.settings (key, value, updated_by) values",
        f"  ('admin', {_q(json.dumps({'admin_email': admin_email}))}::jsonb, 'seed')",
        "on conflict (key) do update set value = excluded.value, updated_at = now();",
        "",
    ]
    payload = settings_payload(cfg)
    rows = [f"  ({_q(k)}, {_q(json.dumps(v, ensure_ascii=False))}::jsonb, 'seed')" for k, v in payload.items()]
    lines += ["insert into public.settings (key, value, updated_by) values", ",\n".join(rows),
              "on conflict (key) do nothing;", ""]
    cells = config_cells(cfg)
    rows = [f"  ({_q(c.subcategory)}, {_q(c.query_template)}, {_q(c.area)}, {c.tier})" for c in cells]
    lines += ["insert into public.search_cells (subcategory, query_template, area, tier) values", ",\n".join(rows),
              "on conflict (subcategory, query_template, area) do nothing;", ""]
    return "\n".join(lines)


def write_seed(cfg: Config, path: Path = ROOT / "supabase" / "seed.sql") -> Path:
    path.write_text(generate_seed_sql(cfg), encoding="utf-8")
    return path
