"""Rebuild fonts.css (base64 @font-face) from the files in fonts/.

    .venv/bin/python teasers/shared/build_fonts.py

To change fonts: drop .woff2 files into fonts/ and edit FACES below. Templates must not load
fonts from the network (brief §13.1), which is why they are embedded as base64.
"""

import base64
from pathlib import Path

HERE = Path(__file__).resolve().parent
FACES = [  # (family, weight, file)
    ("Montserrat", 700, "montserrat-latin-700-normal.woff2"),
    ("Montserrat", 800, "montserrat-latin-800-normal.woff2"),
    ("Inter", 400, "inter-latin-400-normal.woff2"),
    ("Inter", 600, "inter-latin-600-normal.woff2"),
]

css = ["/* GENERATED by build_fonts.py. Fonts: Montserrat and Inter, SIL Open Font License (see fonts/OFL-*.txt). */"]
for family, weight, file in FACES:
    b64 = base64.b64encode((HERE / "fonts" / file).read_bytes()).decode()
    css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:block;"
               f"src:url(data:font/woff2;base64,{b64}) format('woff2');}}")
(HERE / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
print(f"fonts.css: {len(FACES)} faces")
